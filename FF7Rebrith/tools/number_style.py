"""Reviewed numeric phrases only; preserve Thai idioms and nonnumeric words."""

REPLACEMENTS = (
    ("เขตเจ็ด", "เซคเตอร์7"),
    ("เขตศูนย์", "เซคเตอร์0"),
    ("เขตสอง", "เซคเตอร์2"),
    ("เขตห้า", "เซคเตอร์5"),
    ("เครื่องหมายเลขห้า", "เครื่องหมายเลข5"),
    ("หน่วยที่สอง", "หน่วยที่2"),
    ("สองพันปี", "2,000ปี"),
    ("อายุสิบหก", "อายุ16"),
    ("ห้าปี", "5ปี"),
    ("สองปี", "2ปี"),
    ("นับถึงสิบ", "นับถึง10"),
    ("ท่าที่หนึ่ง", "ท่าที่1"),
    ("ท่าที่สอง", "ท่าที่2"),
    ("ท่าที่สาม", "ท่าที่3"),
    ("รอบที่สาม", "รอบที่3"),
    ("ตั้งสองคน", "ตั้ง2คน"),
    ("หนึ่งคน", "1คน"),
    ("ชั้นสอง", "ชั้น2"),
    ("ตั้งร้อยคน", "ตั้ง100คน"),
    ("มุมเก้าสิบองศา", "มุม90องศา"),
    ("ทั้งสอง", "ทั้ง2"),
)


def normalize_numbers(text):
    for before, after in REPLACEMENTS:
        text = text.replace(before, after)
    return text
